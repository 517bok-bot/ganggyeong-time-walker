const { chromium } = require('playwright');
const base = 'http://localhost:3100';
let n = 0; const ok = (c, m) => { if (!c) throw new Error('FAILED: ' + m); n++; console.log('✓', m); };
(async () => {
  const b = await chromium.launch();
  const guest = async () => { const ctx = await b.newContext(); const p = await ctx.newPage(); await p.goto(base + '/login'); await p.getByText('나그네(게스트)로 바로 시작').click(); await p.getByText('기록이 서버에 저장되고 있어요').waitFor(); return p; };
  const call = (p, url, method = 'GET', body) => p.evaluate(async ([u, m, bd]) => { const r = await fetch(u, { method: m, headers: { 'content-type': 'application/json' }, body: bd ? JSON.stringify(bd) : undefined }); return { s: r.status, j: await r.json() }; }, [url, method, body]);
  const A = await guest();
  const bad = await call(A, '/api/letters', 'POST', { body: '연락 주세요 010-1234-5678', open: 'now', isPublic: true });
  ok(bad.s === 422 && /전화번호/.test(bad.j.error), '전화번호가 든 편지 거절');
  const link = await call(A, '/api/letters', 'POST', { body: '여기 보세요 https://example.com', open: 'now', isPublic: true });
  ok(link.s === 422, '링크가 든 편지 거절');
  // UI로 편지 부치기
  await A.goto(base + '/post'); await A.getByLabel('편지 내용').fill('달밤의 강경을 꼭 걸어 보세요. 다음 여행자에게 안부를 전해요.');
  await A.getByText('인장을 찍어 부치기').click(); await A.waitForTimeout(1500);
  const mine = await call(A, '/api/letters');
  ok(mine.j.mine.length === 1, '보낸 편지가 내 편지함에 저장');
  const sealed = await call(A, '/api/letters', 'POST', { body: '일 년 뒤에 열어 보세요, 미래의 여행자님.', open: 'year', isPublic: true });
  ok(sealed.j.ok, '일 년 뒤 공개 편지 저장');
  const id = mine.j.mine[0].id;
  const readers = [await guest(), await guest(), await guest()];
  const r0 = await call(readers[0], '/api/letters');
  ok(r0.j.others.some((l) => l.id === id), '다른 여행자가 공개 편지를 받음');
  ok(!r0.j.others.some((l) => /일 년 뒤/.test(l.body)), '공개 시점 전 편지는 보이지 않음');
  for (const r of readers) await call(r, '/api/letters/report', 'POST', { id });
  const dupReport = await call(readers[0], '/api/letters/report', 'POST', { id });
  ok(dupReport.j.already, '같은 사람의 중복 신고는 한 번만 집계');
  const E = await guest();
  const after = await call(E, '/api/letters');
  ok(!after.j.others.some((l) => l.id === id), '신고 3건 → 자동 숨김');
  const del = await call(A, `/api/letters?id=${id}`, 'DELETE');
  ok(del.j.ok, '내 편지 삭제');
  console.log(`\n${n}개 시간 우체국 서버 검사 통과`);
  await b.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
